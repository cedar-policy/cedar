use smol_str::SmolStr;

// shortcut because we need CST nodes to potentially be empty,
// for example, if part of it failed the parse, we can
// still recover other parts
type Node<N> = super::node::Node<Option<N>>;

/// The set of policy statements that forms a policy set
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Policies(pub Vec<Node<Policy>>);

/// Annotations: application-defined data, as a key-value pair
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Annotation {
    /// key
    pub key: Node<Ident>,
    /// value
    pub value: Option<Node<Str>>,
}

/// Literal strings
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Str {
    /// regular quoted string
    String(SmolStr),
    // this is not generated by the parser at time of comment,
    // but left as future improvement and to clarify the
    // validity of the above `String` form
    /// poorly formed string
    Invalid(SmolStr),
}

/// Policy statement, the main building block of the language
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct PolicyImpl {
    /// Annotations
    pub annotations: Vec<Node<Annotation>>,
    /// policy effect
    pub effect: Node<Ident>,
    /// Variables
    pub variables: Vec<Node<VariableDef>>,
    /// Conditions
    pub conds: Vec<Node<Cond>>,
}

#[derive(Debug, Clone, PartialEq, Eq)]
/// Policy statement - can be an Error node when 'tolerant-ast' feature is switched on
pub enum Policy {
    /// Valid policy CST node
    Policy(PolicyImpl),
    #[cfg(feature = "tolerant-ast")]
    /// Policy that has failed to parse
    PolicyError,
}

/// The variable part of one of the main item of a policy
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct VariableDef {
    /// identifier, expected:
    /// principal, action, resource
    pub variable: Node<Ident>,
    /// type of entity using previously considered `var : type` syntax. This is
    /// not used for anything other than error reporting.
    pub unused_type_name: Option<Node<Name>>,
    /// type of entity using current `var is type` syntax
    pub entity_type: Option<Node<Add>>,
    /// hierarchy of entity
    pub ineq: Option<(RelOp, Node<Expr>)>,
}

/// Any identifier, including special ones
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub enum Ident {
    // Variables
    /// principal
    Principal,
    /// action
    Action,
    /// resource
    Resource,
    /// context
    Context,

    // Other Identifiers
    /// true
    True,
    /// false
    False,
    /// permit
    Permit,
    /// forbid
    Forbid,
    /// when
    When,
    /// unless
    Unless,
    /// in
    In,
    /// has
    Has,
    /// like
    Like,
    /// is
    Is,
    /// if
    If,
    /// then
    Then,
    /// else
    Else,

    // Regular identifiers
    /// user-supplied, in the proper form
    Ident(SmolStr),
    // This is not generated from the parser a time of comment,
    // but here for future improvement and to clarify
    // the validity of the above `Ident` form
    /// user-supplied, not in the proper form
    Invalid(String),
}

/// Conditions: powerful extensions to a policy
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Cond {
    /// initial ident, expected to be "when" or "unless"
    pub cond: Node<Ident>,
    /// related expression. expected to not be `None`, but if it's `None`, that
    /// indicates the body was empty (as in `when {}`), and we can report a good
    /// error message
    pub expr: Option<Node<Expr>>,
}

/// The main computation aspect of a policy, outer
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ExprImpl {
    /// expression content
    pub expr: Box<ExprData>,
}

#[derive(Debug, Clone, PartialEq, Eq)]
/// Expression CST Node
pub enum Expr {
    /// Expression that has been successfully parsed
    Expr(ExprImpl),
    /// To create a tolerant-ast, we keep a node to represented nodes that failed to parse
    #[cfg(feature = "tolerant-ast")]
    ErrorExpr,
}

/// The main computation aspect of a policy, inner
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum ExprData {
    /// || Op
    Or(Node<Or>),
    /// if-then-else
    If(Node<Expr>, Node<Expr>, Node<Expr>),
}
/// Logical Or
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Or {
    /// a singleton is a wrapper for a higher-priority node
    pub initial: Node<And>,
    /// additional elements represent a chained `||` computation
    pub extended: Vec<Node<And>>,
}
/// Logical And
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct And {
    /// a singleton is a wrapper for a higher-priority node
    pub initial: Node<Relation>,
    /// additional elements represent a chained `&&` computation
    pub extended: Vec<Node<Relation>>,
}
/// Comparison relations
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Relation {
    /// Regular relations
    Common {
        /// a singleton is a wrapper for a higher-priority node
        initial: Node<Add>,
        /// additional elements represent chained `>`, `<`, etc. computation
        extended: Vec<(RelOp, Node<Add>)>,
    },
    /// Built-in 'has' operation
    Has {
        /// element that may have a field
        target: Node<Add>,
        /// a field the element may have
        field: Node<Add>,
    },
    /// Built-in 'like' operation
    Like {
        /// element to test
        target: Node<Add>,
        /// pattern to match on
        pattern: Node<Add>,
    },
    /// Built-in '.. is .. (in ..)?' operation
    IsIn {
        /// element that may be an entity type and `in` an entity
        target: Node<Add>,
        /// entity type to check for
        entity_type: Node<Add>,
        /// entity that the target may be `in`
        in_entity: Option<Node<Add>>,
    },
}

/// The operation involved in a comparision
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum RelOp {
    /// <
    Less,
    /// <=
    LessEq,
    /// >=
    GreaterEq,
    /// >
    Greater,
    /// !=
    NotEq,
    /// ==
    Eq,
    /// in
    In,
    /// =
    ///
    /// This is always invalid, but included so we can give a nice error suggesting '==' instead
    InvalidSingleEq,
}

/// Allowed Ops for Add
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum AddOp {
    /// +
    Plus,
    /// -
    Minus,
}

/// Allowed Ops for Mult
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum MultOp {
    /// *
    Times,
    /// /
    Divide,
    /// %
    Mod,
}

/// Allowed Ops for Neg
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum NegOp {
    /// count of `!`'s
    Bang(u8),
    /// too many `!`'s
    OverBang,
    /// count of `-`'s
    Dash(u8),
    /// too many `-`'s
    OverDash,
}

/// Additive arithmetic
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Add {
    /// a singleton is a wrapper for a higher-priority node
    pub initial: Node<Mult>,
    /// additional elements represent a chained `+`, `-`, etc. computation
    pub extended: Vec<(AddOp, Node<Mult>)>,
}
/// Multiplicative arithmetic
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Mult {
    /// a singleton is a wrapper for a higher-priority node
    pub initial: Node<Unary>,
    /// additional elements represent a chained `*`, `/`, etc. computation
    pub extended: Vec<(MultOp, Node<Unary>)>,
}
/// Unary negations
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Unary {
    /// the negation operation, if any
    pub op: Option<NegOp>,
    /// higher-priority node the negation is applied to
    pub item: Node<Member>,
}
/// Members on a primary item, accessed with '.'
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Member {
    /// Main element
    pub item: Node<Primary>,
    /// fields, indexes, etc.
    pub access: Vec<Node<MemAccess>>,
}
/// Forms of members and their accessors
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum MemAccess {
    /// field identifier
    Field(Node<Ident>),
    /// function call
    Call(Vec<Node<Expr>>),
    /// index of a member
    Index(Node<Expr>),
}
/// Low-level elements like literals
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Primary {
    /// Literal
    Literal(Node<Literal>),
    /// References to entities
    Ref(Node<Ref>),
    /// Constructed elements with names
    Name(Node<Name>),
    /// Template Slots
    Slot(Node<Slot>),
    /// Parentheses
    Expr(Node<Expr>),
    /// Constructed array
    EList(Vec<Node<Expr>>),
    /// Constructed record
    RInits(Vec<Node<RecInit>>),
}

/// UID and Type of named items
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub struct Name {
    /// path, like: "name0::name1::name"
    pub path: Vec<Node<Ident>>,
    /// Singleton name
    pub name: Node<Ident>,
}
/// Reference to an entity
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Ref {
    /// UID
    Uid {
        /// The path/type of an entity
        path: Node<Name>,
        /// EID, quoted name
        eid: Node<Str>,
    },
    /// Lookup references
    Ref {
        /// The path/type of an entity
        path: Node<Name>,
        /// The indicated fields of the entity
        rinits: Vec<Node<RefInit>>,
    },
}
/// Elements in a ref: `field: data`
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct RefInit(pub Node<Ident>, pub Node<Literal>);
/// Elements of records: `field_from_expr: data_from_expr`
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct RecInit(pub Node<Expr>, pub Node<Expr>);

/// Raw values
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Literal {
    /// true
    True,
    /// false
    False,
    /// some integer
    Num(u64),
    /// some String
    Str(Node<Str>),
}

/// Template Slots
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Slot {
    /// Slot for Principal Constraints
    Principal,
    /// Slot for Resource Constraints
    Resource,
    /// Slot other than one of the valid slots
    Other(SmolStr),
}

impl Slot {
    /// Check if a slot matches a scope variable.
    pub fn matches(&self, var: crate::ast::Var) -> bool {
        matches!(
            (self, var),
            (Slot::Principal, crate::ast::Var::Principal)
                | (Slot::Resource, crate::ast::Var::Resource)
        )
    }
}

/// Drop without recursing on the stack
///
/// A custom drop is required to ensure that we don't stack overflow while
/// dropping a CST after detecting that it's too deep. It also protects against
/// a more subtle case where lalrpop returns with an error after constructing a
/// deep CST. In this case we never have a chance to check the depth before it's
/// dropped.
impl Drop for Expr {
    fn drop(&mut self) {
        if let Some(data) = take_expr_data(self) {
            stack_safe_drop::drop_expr_data(data);
        }
    }
}

fn take_expr_data(expr: &mut Expr) -> Option<ExprData> {
    match expr {
        Expr::Expr(e) => Some(std::mem::replace(
            e.expr.as_mut(),
            ExprData::Or(Node::new(None)),
        )),
        #[cfg(feature = "tolerant-ast")]
        Expr::ErrorExpr => None,
    }
}

#[yaspar_macros::stack_safe]
mod stack_safe_drop {
    use super::{
        take_expr_data, Add, And, Expr, ExprData, MemAccess, Member, Mult, Node, Or, Primary,
        RecInit, Relation, Unary,
    };

    fn drop_expr(expr_node: Node<Expr>) {
        let Some(mut expr) = expr_node.node else {
            return;
        };
        if let Some(data) = take_expr_data(&mut expr) {
            drop_expr_data(data);
        }
    }

    pub(super) fn drop_expr_data(data: ExprData) {
        match data {
            ExprData::Or(or) => drop_or(or),
            ExprData::If(cond, then_expr, else_expr) => {
                drop_expr(cond);
                drop_expr(then_expr);
                drop_expr(else_expr);
            }
        }
    }

    fn drop_or(or_node: Node<Or>) {
        let Some(Or { initial, extended }) = or_node.node else {
            return;
        };
        drop_and(initial);
        for ext in extended {
            drop_and(ext);
        }
    }

    fn drop_and(and_node: Node<And>) {
        let Some(And { initial, extended }) = and_node.node else {
            return;
        };
        drop_relation(initial);
        for ext in extended {
            drop_relation(ext);
        }
    }

    fn drop_relation(rel_node: Node<Relation>) {
        let Some(rel) = rel_node.node else {
            return;
        };
        match rel {
            Relation::Common { initial, extended } => {
                drop_add(initial);
                for (_, ext) in extended {
                    drop_add(ext);
                }
            }
            Relation::Has { target, field } => {
                drop_add(target);
                drop_add(field);
            }
            Relation::Like { target, pattern } => {
                drop_add(target);
                drop_add(pattern);
            }
            Relation::IsIn {
                target,
                entity_type,
                in_entity,
            } => {
                drop_add(target);
                drop_add(entity_type);
                if let Some(in_entity) = in_entity {
                    drop_add(in_entity);
                }
            }
        }
    }

    fn drop_add(add_node: Node<Add>) {
        let Some(Add { initial, extended }) = add_node.node else {
            return;
        };
        drop_mult(initial);
        for (_, ext) in extended {
            drop_mult(ext);
        }
    }

    fn drop_mult(mult_node: Node<Mult>) {
        let Some(Mult { initial, extended }) = mult_node.node else {
            return;
        };
        drop_unary(initial);
        for (_, ext) in extended {
            drop_unary(ext);
        }
    }

    fn drop_unary(unary_node: Node<Unary>) {
        let Some(Unary { item, .. }) = unary_node.node else {
            return;
        };
        drop_member(item);
    }

    fn drop_member(mem_node: Node<Member>) {
        let Some(Member { item, access }) = mem_node.node else {
            return;
        };
        drop_primary(item);
        for acc_node in access {
            drop_mem_access(acc_node);
        }
    }

    fn drop_mem_access(acc_node: Node<MemAccess>) {
        let Some(acc) = acc_node.node else {
            return;
        };
        match acc {
            MemAccess::Call(args) => {
                for arg in args {
                    drop_expr(arg);
                }
            }
            MemAccess::Index(idx) => drop_expr(idx),
            MemAccess::Field(_) => {}
        }
    }

    fn drop_primary(prim_node: Node<Primary>) {
        let Some(prim) = prim_node.node else {
            return;
        };
        match prim {
            Primary::Expr(e) => drop_expr(e),
            Primary::EList(elts) => {
                for elt in elts {
                    drop_expr(elt);
                }
            }
            Primary::RInits(inits) => {
                for init_node in inits {
                    if let Some(RecInit(key, value)) = init_node.node {
                        drop_expr(key);
                        drop_expr(value);
                    }
                }
            }
            Primary::Literal(_) | Primary::Ref(_) | Primary::Name(_) | Primary::Slot(_) => {}
        }
    }
}
